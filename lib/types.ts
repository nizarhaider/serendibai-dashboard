  id: string;
  name: string;
  company_name: string;
  company_url: string;
  system_prompt: string;
  voice: string;
  languages: string[];
  tools: string[];
  max_calls: number;
  phone_number_id: string;
  status: string;
  version: number;
  deployed_version: number;
  heartbeat_at: string | null;
  telemetry: Record<string, number | string>;
